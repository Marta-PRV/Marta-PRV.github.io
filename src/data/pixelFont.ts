/**
 * Mini tipografía pixel de 3x5 para los monogramas de las tecnologías.
 * Cada glifo son 5 filas de 3 bits ('1' = píxel encendido).
 */
const glyphs: Record<string, string[]> = {
  A: ['010', '101', '111', '101', '101'],
  B: ['110', '101', '110', '101', '110'],
  C: ['011', '100', '100', '100', '011'],
  D: ['110', '101', '101', '101', '110'],
  E: ['111', '100', '110', '100', '111'],
  G: ['011', '100', '101', '101', '011'],
  H: ['101', '101', '111', '101', '101'],
  I: ['111', '010', '010', '010', '111'],
  J: ['001', '001', '001', '101', '010'],
  K: ['101', '101', '110', '101', '101'],
  L: ['100', '100', '100', '100', '111'],
  M: ['101', '111', '111', '101', '101'],
  N: ['110', '101', '101', '101', '101'],
  O: ['010', '101', '101', '101', '010'],
  P: ['110', '101', '110', '100', '100'],
  Q: ['010', '101', '101', '111', '011'],
  R: ['110', '101', '110', '101', '101'],
  S: ['011', '100', '010', '001', '110'],
  T: ['111', '010', '010', '010', '010'],
  U: ['101', '101', '101', '101', '111'],
  V: ['101', '101', '101', '101', '010'],
  X: ['101', '101', '010', '101', '101'],
  Y: ['101', '101', '010', '010', '010'],
  '0': ['111', '101', '101', '101', '111'],
  '1': ['010', '110', '010', '010', '111'],
  '2': ['110', '001', '010', '100', '111'],
  '3': ['110', '001', '010', '001', '110'],
  '#': ['101', '111', '101', '111', '101'],
  '+': ['000', '010', '111', '010', '000'],
  '<': ['001', '010', '100', '010', '001'],
  '>': ['100', '010', '001', '010', '100'],
  '/': ['001', '001', '010', '100', '100'],
};

/** Devuelve los píxeles encendidos (x, y) de un texto, ya centrado en una rejilla de `size` x `size`. */
export function renderMark(text: string, size = 16): { x: number; y: number }[] {
  const chars = [...text.toUpperCase()].filter((c) => glyphs[c]);
  const width = chars.length * 3 + Math.max(0, chars.length - 1);
  const startX = Math.floor((size - width) / 2);
  const startY = Math.floor((size - 5) / 2);
  const pixels: { x: number; y: number }[] = [];
  chars.forEach((c, i) => {
    glyphs[c].forEach((row, y) => {
      [...row].forEach((bit, x) => {
        if (bit === '1') pixels.push({ x: startX + i * 4 + x, y: startY + y });
      });
    });
  });
  return pixels;
}
